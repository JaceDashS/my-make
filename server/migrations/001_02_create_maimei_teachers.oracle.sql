CREATE SEQUENCE MAIMEI_TEACHERS_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE SEQUENCE MAIMEI_TEACHER_CODE_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE OR REPLACE TRIGGER MAIMEI_TEACHERS_BIR
BEFORE INSERT ON MAIMEI_TEACHERS
FOR EACH ROW
BEGIN
    IF :NEW.TEACHER_ID IS NULL THEN
        SELECT MAIMEI_TEACHERS_SEQ.NEXTVAL
          INTO :NEW.TEACHER_ID
          FROM DUAL;
    END IF;

    IF :NEW.TEACHER_CODE IS NULL THEN
        SELECT 'TC' || LPAD(MAIMEI_TEACHER_CODE_SEQ.NEXTVAL, 10, '0')
          INTO :NEW.TEACHER_CODE
          FROM DUAL;
    END IF;

    IF :NEW.CREATED_AT IS NULL THEN
        :NEW.CREATED_AT := SYSTIMESTAMP;
    END IF;

    IF :NEW.UPDATED_AT IS NULL THEN
        :NEW.UPDATED_AT := SYSTIMESTAMP;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER MAIMEI_TEACHERS_BUR
BEFORE UPDATE ON MAIMEI_TEACHERS
FOR EACH ROW
BEGIN
    :NEW.UPDATED_AT := SYSTIMESTAMP;
END;
/

CREATE OR REPLACE TRIGGER MAIMEI_TEACHERS_BUC
BEFORE UPDATE OF TEACHER_CODE ON MAIMEI_TEACHERS
FOR EACH ROW
BEGIN
    RAISE_APPLICATION_ERROR(-20001, 'TEACHER_CODE is immutable.');
END;
/

CREATE INDEX IDX_MAIMEI_TEACHERS_ACADEMY_CODE
    ON MAIMEI_TEACHERS (ACADEMY_CODE);

CREATE INDEX IDX_MAIMEI_TEACHERS_STATUS_CODE
    ON MAIMEI_TEACHERS (STATUS_CODE);
